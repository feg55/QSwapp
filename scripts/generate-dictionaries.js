#!/usr/bin/env node

"use strict";

const crypto = require("node:crypto");
const fs = require("node:fs");
const https = require("node:https");
const path = require("node:path");

const projectRoot = path.resolve(__dirname, "..");
const metadata = require(path.join(projectRoot, "dictionary-sources.json"));
const checkOnly = process.argv.includes("--check");
const outputArgumentIndex = process.argv.indexOf("--output");
const outputPath =
  outputArgumentIndex >= 0
    ? path.resolve(process.argv[outputArgumentIndex + 1])
    : path.join(projectRoot, "dictionaries.js");
const sourceArgumentIndex = process.argv.indexOf("--source-dir");
const sourceDirectory =
  sourceArgumentIndex >= 0
    ? path.resolve(process.argv[sourceArgumentIndex + 1])
    : null;

if (sourceArgumentIndex >= 0 && !process.argv[sourceArgumentIndex + 1]) {
  throw new Error("После --source-dir нужен путь к исходным таблицам");
}

if (outputArgumentIndex >= 0 && !process.argv[outputArgumentIndex + 1]) {
  throw new Error("После --output нужен путь к результату");
}

function download(url) {
  return new Promise((resolve, reject) => {
    https
      .get(url, { headers: { "user-agent": "layout-fixer-generator" } }, (response) => {
        if (
          response.statusCode >= 300 &&
          response.statusCode < 400 &&
          response.headers.location
        ) {
          response.resume();
          download(response.headers.location).then(resolve, reject);
          return;
        }

        if (response.statusCode !== 200) {
          response.resume();
          reject(new Error(`Не удалось скачать ${url}: HTTP ${response.statusCode}`));
          return;
        }

        const chunks = [];
        response.on("data", (chunk) => chunks.push(chunk));
        response.on("end", () => resolve(Buffer.concat(chunks)));
        response.on("error", reject);
      })
      .on("error", reject);
  });
}

function sourceUrl(source) {
  return (
    `https://raw.githubusercontent.com/hermitdave/FrequencyWords/` +
    `${metadata.commit}/${source.path}`
  );
}

async function readSource(source) {
  if (!sourceDirectory) {
    return download(sourceUrl(source));
  }

  return fs.readFileSync(
    path.join(sourceDirectory, path.basename(source.path))
  );
}

function verifyChecksum(buffer, source) {
  const actual = crypto.createHash("sha256").update(buffer).digest("hex");

  if (actual !== source.sha256) {
    throw new Error(
      `Checksum ${source.path} не совпал: ожидался ${source.sha256}, получен ${actual}`
    );
  }
}

function filteredRows(buffer, source) {
  verifyChecksum(buffer, source);
  const alphabet = new RegExp(source.alphabet, "u");
  const rows = buffer
    .toString("utf8")
    .trim()
    .split(/\r?\n/u)
    .filter((row) => {
      const separator = row.lastIndexOf(" ");
      return separator > 0 && alphabet.test(row.slice(0, separator));
    });

  if (rows.length !== source.expectedEntries) {
    throw new Error(
      `${source.path}: ожидалось ${source.expectedEntries} строк, получено ${rows.length}`
    );
  }

  return rows.join("\n");
}

function renderDictionary(englishData, russianData) {
  return `/*
 * Generated by scripts/generate-dictionaries.js. Do not edit manually.
 * Frequency data: hermitdave/FrequencyWords, OpenSubtitles 2018 lists.
 * Upstream commit: ${metadata.commit}
 * Data license: CC BY-SA 4.0. See THIRD_PARTY_NOTICES.md.
 */
(function initializeDictionaries(root, factory) {
  const isCommonJs = typeof module === "object" && module.exports;
  const api = !isCommonJs && root.LayoutFixerDictionaries
    ? root.LayoutFixerDictionaries
    : factory();

  if (isCommonJs) {
    module.exports = api;
  } else {
    root.LayoutFixerDictionaries = api;
  }
})(typeof globalThis !== "undefined" ? globalThis : this, function createDictionaries() {
  "use strict";

  const ENGLISH_DATA = \`${englishData}\`;

  const RUSSIAN_DATA = \`${russianData}\`;

  function parseDictionary(serialized) {
    const words = new Map();
    let maximumFrequency = 0;

    for (const row of serialized.split("\\n")) {
      const separator = row.lastIndexOf(" ");
      const word = row.slice(0, separator);
      const frequency = Number(row.slice(separator + 1));

      words.set(word, frequency);
      maximumFrequency = Math.max(maximumFrequency, frequency);
    }

    return { words, maximumFrequency, size: words.size };
  }

  return {
    english: parseDictionary(ENGLISH_DATA),
    russian: parseDictionary(RUSSIAN_DATA),
    source: {
      repository: ${JSON.stringify(metadata.repository)},
      commit: ${JSON.stringify(metadata.commit)},
      license: ${JSON.stringify(metadata.license)}
    }
  };
});
`;
}

async function main() {
  const [englishBuffer, russianBuffer] = await Promise.all([
    readSource(metadata.sources.english),
    readSource(metadata.sources.russian)
  ]);
  const generated = renderDictionary(
    filteredRows(englishBuffer, metadata.sources.english),
    filteredRows(russianBuffer, metadata.sources.russian)
  );

  if (checkOnly) {
    if (fs.readFileSync(outputPath, "utf8") !== generated) {
      throw new Error(
        "dictionaries.js отличается от воспроизводимого результата генератора"
      );
    }
    console.log("dictionaries.js воспроизводим, checksums совпали");
    return;
  }

  fs.writeFileSync(outputPath, generated);
  console.log(
    `Создан dictionaries.js: ` +
      `${metadata.sources.english.expectedEntries} EN, ` +
      `${metadata.sources.russian.expectedEntries} RU`
  );
}

main().catch((error) => {
  console.error(error.message);
  process.exitCode = 1;
});
